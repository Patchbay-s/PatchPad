//! Les libellés n'utilisent que des caractères Latin-1 / WinAnsi, pour que le PDF (polices
//! standard Helvetica) les affiche tels quels : « Croix » plutôt que « ✕ ».

use serde::Deserialize;

use crate::model::{BatteryStatus, Button, Connection, Family};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Lang {
    Fr,
    En,
}

pub struct Text {
    pub lang: Lang,
}

macro_rules! texts {
    ($($name:ident => $fr:expr, $en:expr;)*) => {
        impl Text {
            $(pub fn $name(&self) -> &'static str {
                match self.lang {
                    Lang::Fr => $fr,
                    Lang::En => $en,
                }
            })*
        }
    };
}

